# 牌背（11×7 条纹）
CARD_BACK = ("10101010101",) * 7


def _render(rows: tuple, scale: int = 1, fg: int = 255, bg: int = 0
            ) -> ImageData:
    """位图行 → RGBA ImageData（白字形黑底；整数放大）。"""
    h, w = len(rows), len(rows[0])
    out = bytearray(w * scale * h * scale * 4)
    for y in range(h):
        for x in range(w):
            v = fg if rows[y][x] == "1" else bg
            px = bytes((v, v, v, 255))
            for dy in range(scale):
                start = ((y * scale + dy) * (w * scale) + x * scale) * 4
                out[start:start + 4 * scale] = px * scale
    return ImageData.from_rgba_bytes(w * scale, h * scale, bytes(out))


def builtin_digit_templates(scale: int = 1) -> dict:
    return {ch: _render(rows, scale) for ch, rows in GLYPHS_5X7.items()}


def builtin_rank_templates(scale: int = 1) -> dict:
    out = {}
    for ch in "23456789":
        out[ch] = _render(GLYPHS_5X7[ch], scale)
    for ch, rows in RANK_GLYPHS.items():
        out[ch] = _render(rows, scale)
    return out


def builtin_suit_templates(scale: int = 1) -> dict:
    return {ch: _render(rows, scale) for ch, rows in SUIT_GLYPHS.items()}


def builtin_card_back(scale: int = 1) -> ImageData:
    return _render(CARD_BACK, scale)
